export const SELF_CONTAINED_RULES = `每条记忆必须能单独读懂：离开这次对话、离开其它条目，只读这一条，也要能看出说的是哪个对象、做了什么、结果如何。

硬规则：
1. 不许以这些词开头：但是、但、所以、因此、另外、此外、并且、而、且、同时、于是、然后、还有、以及、总之。
2. 不许用指代词代替本条之外的对象。「这一步」「该步」「上述」「上面」「前者」「后者」「该结论」「这个改动」「那条」「该条」「它」「此」都不许出现；要写成具体名词，具体到哪个文件、哪个参数、哪张表、哪个服务、哪个人。
3. 时间写绝对日期（YYYY-MM-DD），不写今天、昨天、刚才、最近、上次。
4. 一条只讲一件事。两件并列的事不许接成因果关系，除非原文明确这么写。
5. 不许写元说明：「此条被某某取代」「见上一条」「正文见某节」「同上」「（略）」一律不写；取代关系由 supersedes 字段表达，不进正文。
   禁止在正文里复述本规则的原文或字面例子——不要写「此条被某某取代」「见上一条」这类字样作为举例或引用，要说明这类规则时用转述，不要照抄字面串。
6. 结论要带可核对的坐标：文件:行号、命令、路径、版本号、实测数字。拿不出坐标就不要写「已验证」「已确认」「实测过」。
7. 主语写清是谁：说这话的人、某个插件、某台机器、某个服务，不能用「我」「这边」「双方」含糊带过。`;

export const SPLIT_RULES = `拆出来的每一段都必须能独立成句：
- 切点只在句号或换行之后；不许切在分号之后，也不许把一句话从中间切开。
- 切点不许落在引号（「」『』“”""）、括号（（）()）、代码围栏（\`\`\`）内部。
- 每段不许以这些词开头：这、该、它、此、那、上述、上面、这份、本文件、该目录、这个仓库、这个插件；要写成本段真正的对象。
- 原句共用的主语要在每段重写出来，不许让后一段只靠前一段的主语撑着。
- 原句以「但是」「所以」「因此」这类词起头的，先写成本段真正的对象再起步。
- 每段不少于 25 个字符，不足就并进相邻的那一段。
- 文件名、行号、数字只提供定位。缺完整陈述（例如只有「lib/gate.js 的」）的片段即使带路径也判 redo。
- 纯过程性状态（本轮、本轮工具不可用、这次失败）标 skip，不进库。
- 不许产出只有过渡作用、没有事实的段落。`;

